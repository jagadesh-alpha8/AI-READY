const fs = require('fs');
const assert = require('assert/strict');
const resolver = require('node:module').createRequire(require('node:path').resolve(__dirname, '../frontend/package.json'));
const { chromium } = process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES ? require(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES + '/playwright') : resolver('playwright');
const base = process.env.CAPABILITY_UI_URL || 'http://127.0.0.1:3015';
if (!['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw Error('Only local synthetic UI testing is supported.');
if (!process.argv[2]) throw Error('Supply the synthetic fixture JSON path.');
(async () => {
  const run = JSON.parse(fs.readFileSync(process.argv[2]));
  const sid = '22222222-2222-4222-8222-222222222222';
  const browser = await chromium.launch({ headless: true, ...(process.env.CAPABILITY_CHROMIUM_EXECUTABLE ? { executablePath: process.env.CAPABILITY_CHROMIUM_EXECUTABLE, args: ['--no-sandbox', '--single-process', '--no-zygote', '--disable-gpu', '--use-gl=disabled'] } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; const writes = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(() => localStorage.setItem('aios_token', 'synthetic-test-only'));
  await page.route('**/api/v1/**', async route => {
    const request = route.request(); const path = new URL(request.url()).pathname;
    if (request.method() !== 'GET') writes.push(path);
    let data = [];
    if (path === '/api/v1/auth/me') data = { id: 'tester', username: 'tester', name: 'Synthetic tester', role: 'iqac_coordinator', institution_id: 'institution1', is_active: true };
    else if (path === '/api/v1/sprints') data = [{ id: sid, institution_id: 'institution1', institution_name: 'Synthetic College — UI Test', name: 'Synthetic', sprint_code: 'SYNTHETIC-01', academic_year: '2025-26', status: 'reviewing', created_at: '2026-10-30T10:00:00Z' }];
    else if (path === '/api/v1/auth/guide-status') data = { steps: [], total_steps: 0, completed_count: 0, skipped_count: 0, is_dismissed: true, menu_tours: {} };
    else if (path.endsWith('/capability-runs')) data = { results: [run], next: null, previous: null, enabled: false };
    else if (path.endsWith('/recommendations')) data = { results: [], next: null, previous: null, enabled: false };
    else if (path.endsWith('/capability-runs/' + run.id)) data = run;
    else if (path === '/api/v1/dashboard') data = { active_sprints: 1, institution_count: 1, sprints: [] };
    else if (path.endsWith('/summary')) data = { pending_count: 0 };
    return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(data) });
  });
  await page.goto(`${base}/sprint/${sid}/score`);
  await page.getByRole('heading', { name: 'All 36 indicators' }).waitFor();
  assert.equal(await page.locator('section[aria-label="Indicator evidence"] > details').count(), 36);
  assert.match(await page.locator('main').innerText(), /Synthetic College/);
  assert.match(await page.locator('main').innerText(), /Next overall threshold/);
  if (process.env.CAPABILITY_UI_SCREENSHOTS) await page.screenshot({ path: process.env.CAPABILITY_UI_SCREENSHOTS + '/standing-desktop.png', fullPage: true });
  await page.getByRole('link', { name: 'Recommendations', exact: true }).last().click();
  await page.getByRole('heading', { name: 'Requirement-linked actions' }).waitFor();
  assert.match(await page.locator('main').innerText(), /Evidence requests/);
  if (process.env.CAPABILITY_UI_SCREENSHOTS) await page.screenshot({ path: process.env.CAPABILITY_UI_SCREENSHOTS + '/actions-desktop.png', fullPage: true });
  await page.getByRole('link', { name: 'Report', exact: true }).click();
  await page.getByRole('button', { name: 'Download printable HTML report' }).waitFor();
  assert.match(await page.locator('main').innerText(), /No baseline approval/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(300);
  if (process.env.CAPABILITY_UI_SCREENSHOTS) await page.screenshot({ path: process.env.CAPABILITY_UI_SCREENSHOTS + '/report-mobile.png', fullPage: true });
  const overflow = await page.locator('main').evaluate(el => ({ width: el.clientWidth, scroll: el.scrollWidth }));
  if (overflow.scroll > overflow.width + 1) console.log(await page.locator('main').evaluate(el => [...el.querySelectorAll('*')].filter(e=>e.getBoundingClientRect().right>el.getBoundingClientRect().right+1).slice(0,8).map(e=>({tag:e.tagName,text:e.textContent.slice(0,50),cls:e.className}))));
  assert.ok(overflow.scroll <= overflow.width + 1, JSON.stringify(overflow));
  assert.deepEqual(errors, []);
  assert.deepEqual(writes, []);
  console.log('Browser check passed: 36 indicators; recommendations/report navigation; mobile width; no runtime errors; no POSTs.');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
