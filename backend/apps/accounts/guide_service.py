def resolve_accessible_institution(user: User, institution_id: Optional[str] = None) -> Optional[Institution]:
    accessible_ids = get_accessible_institution_ids(user)
    if institution_id:
        if accessible_ids is not None and str(institution_id) not in [str(i) for i in accessible_ids]:
            return None
        return Institution.objects.filter(id=institution_id).first()

    if user.institution_id:
        return user.institution

    if accessible_ids is not None:
        return Institution.objects.filter(id__in=accessible_ids).first()

    return Institution.objects.first()


def resolve_accessible_sprint(
    user: User, institution: Optional[Institution], sprint_id: Optional[str] = None
) -> Optional[Sprint]:
    accessible_ids = get_accessible_institution_ids(user)
    qs = Sprint.objects.all()
    if accessible_ids is not None:
        qs = qs.filter(institution_id__in=accessible_ids)

    if sprint_id:
        return qs.filter(id=sprint_id).first()

    if institution:
        inst_sprint = qs.filter(institution=institution).first()
        if inst_sprint:
            return inst_sprint

    return qs.first()


def get_user_guide_state(user: User, institution: Optional[Institution], sprint: Optional[Sprint]) -> UserGuideState:
    """Fetch or create persisted guide preferences for (user, institution, sprint)."""
    try:
        state = UserGuideState.objects.filter(user=user, institution=institution, sprint=sprint).first()
        if not state:
            state, _ = UserGuideState.objects.get_or_create(
                user=user,
                institution=institution,
                sprint=sprint,
                defaults={'skipped_steps': [], 'is_dismissed': False, 'menu_tours': {}},
            )
        return state
    except Exception as exc:
        logger.warning('Failed to query or create UserGuideState: %s', exc)
        return UserGuideState(user=user, institution=institution, sprint=sprint, skipped_steps=[], is_dismissed=False, menu_tours={})


def get_guide_status(
    user: User,
    sprint_id: Optional[str] = None,
    institution_id: Optional[str] = None,
) -> Dict[str, Any]:
    """Derive full onboarding guide progress and active step for the user.

    Completion is dynamically computed from underlying DB records.
    Skip state is retrieved from UserGuideState.
    """
    institution = resolve_accessible_institution(user, institution_id)
    sprint = resolve_accessible_sprint(user, institution, sprint_id)
    if sprint and not institution:
        institution = sprint.institution

    # Load skipped steps and dismissed state for this scope
    guide_state = get_user_guide_state(user, institution, sprint)
    skipped_step_keys = set(guide_state.skipped_steps or [])

    # If on a sprint, step 1 (institution_dna) can also reflect institution-level skip
    if sprint and institution:
        inst_state = UserGuideState.objects.filter(
            user=user, institution=institution, sprint__isnull=True
        ).first()
        if inst_state and 'institution_dna' in (inst_state.skipped_steps or []):
            skipped_step_keys.add('institution_dna')

    is_dismissed = guide_state.is_dismissed

    menu_tours: Dict[str, Any] = {}
    if institution:
        base_state = UserGuideState.objects.filter(
            user=user, institution=institution, sprint__isnull=True
        ).first()
        if base_state and base_state.menu_tours:
            menu_tours.update(base_state.menu_tours)
    elif not sprint:
        base_state = UserGuideState.objects.filter(
            user=user, institution__isnull=True, sprint__isnull=True
        ).first()
        if base_state and base_state.menu_tours:
            menu_tours.update(base_state.menu_tours)
    if guide_state and getattr(guide_state, 'menu_tours', None):
        menu_tours.update(guide_state.menu_tours)

    steps: List[Dict[str, Any]] = []
    completed_count = 0
    skipped_count = 0

    sprint_id_str = str(sprint.id) if sprint else ''

    for cfg in STEP_CONFIGS:
        step_id = cfg['id']
        num = cfg['number']
        title = cfg['title']
        purpose = cfg['purpose']
        target_path = cfg['target_path_template'].format(sprint_id=sprint_id_str)
        action_label = cfg['action_label_default']
        block_reason = None
        details: Dict[str, Any] = {}

        # Role authorization check:
        # All 3 consolidated roles (super_admin, consultant, iqac_coordinator)
        # can perform the 11 audit workflow steps, scoped to their institution.
        is_authorized = True

        status = 'not_started'

        if step_id == 'institution_dna':
            if institution:
                has_details = bool(
                    institution.student_count
                    or institution.faculty_count
                    or institution.digital_maturity_level
                    or institution.departments.exists()
                    or institution.leaders.exists()
                    or institution.systems.exists()
                )
                details = {
                    'institution_id': str(institution.id),
                    'institution_name': institution.name,
                    'has_details': has_details,
                    'departments_count': institution.departments.count(),
                    'leaders_count': institution.leaders.count(),
                }
                if has_details:
                    status = 'completed'
                    action_label = 'Review Institution DNA'
                else:
                    status = 'in_progress'
                    action_label = 'Complete Institution DNA'
                target_path = f'/institution-dna/{institution.id}'
            else:
                status = 'not_started'
                action_label = 'Set up Institution DNA'
                target_path = '/institution-dna'

        elif step_id == 'sprint_setup':
            if sprint:
                status = 'completed'
                action_label = 'Manage Sprint'
                details = {
                    'sprint_id': str(sprint.id),
                    'sprint_code': sprint.sprint_code,
                    'sprint_name': sprint.name or sprint.sprint_code,
                    'sprint_status': sprint.status,
                    'mode': sprint.mode,
                }
                target_path = f'/sprint/{sprint.id}/upload'
            else:
                has_sprints = Sprint.objects.filter(institution=institution).exists() if institution else False
                details = {'has_sprints': has_sprints}
                if has_sprints:
                    status = 'in_progress'
                    action_label = 'Select Sprint'
                else:
                    status = 'not_started'
                    action_label = 'Create Sprint'
                target_path = '/sprint/setup'

        elif step_id == 'upload_documents':
            if not sprint:
                status = 'not_started'
                block_reason = 'Select or create a sprint first (Step 2).'
            else:
                active_docs = sprint.documents.filter(superseded_at__isnull=True).exclude(status=Document.Status.REJECTED)
                doc_count = active_docs.count()
                details = {
                    'documents_count': doc_count,
                    'pending_count': active_docs.filter(status=Document.Status.PENDING).count(),
                }
                if doc_count > 0:
                    status = 'completed'
                    action_label = 'View / Upload Documents'
                else:
                    status = 'not_started'
                    action_label = 'Upload Documents'

        elif step_id == 'monitor_processing':
            active_docs = sprint.documents.filter(superseded_at__isnull=True).exclude(status=Document.Status.REJECTED) if sprint else Document.objects.none()
            doc_count = active_docs.count()
            if not sprint or doc_count == 0:
                status = 'not_started'
                block_reason = 'Upload documents first (Step 3).'
            else:
                jobs = ExtractionJob.objects.filter(sprint=sprint, document__in=active_docs)
                failed_jobs = jobs.filter(status=ExtractionJob.Status.FAILED).count()
                partial_jobs = jobs.filter(completeness=ExtractionJob.Completeness.PARTIAL).count()
                unreadable_pages = sum(j.unreadable_pages for j in jobs)
                running_jobs = jobs.filter(
                    status__in=[
                        ExtractionJob.Status.PENDING,
                        ExtractionJob.Status.RUNNING,
                        ExtractionJob.Status.RETRYING,
                    ]
                ).count()
                completed_jobs = jobs.filter(status=ExtractionJob.Status.COMPLETED).count()
                failed_docs = active_docs.filter(status=Document.Status.FAILED).count()

                details = {
                    'total_jobs': jobs.count(),
                    'completed_jobs': completed_jobs,
                    'failed_jobs': failed_jobs,
                    'partial_jobs': partial_jobs,
                    'unreadable_pages': unreadable_pages,
                    'running_jobs': running_jobs,
                }

                if failed_jobs > 0 or partial_jobs > 0 or unreadable_pages > 0 or failed_docs > 0:
                    status = 'needs_attention'
                    action_label = 'Retry / Review Issues'
                elif running_jobs > 0 or (jobs.count() == 0 and doc_count > 0):
                    status = 'in_progress'
                    action_label = 'View Processing Monitor'
                elif completed_jobs >= doc_count and doc_count > 0 and unreadable_pages == 0:
                    status = 'completed'
                    action_label = 'View Monitor Results'
                else:
                    status = 'in_progress'
                    action_label = 'Monitor Processing'

        elif step_id == 'facts_review':
            if not sprint:
                status = 'not_started'
                block_reason = 'Select a sprint first (Step 2).'
            else:
                facts = sprint.facts.all()
                total_facts = facts.count()
                unreviewed = facts.filter(status=ExtractedFact.Status.EXTRACTED).count()
                confirmed = facts.filter(
                    status__in=[ExtractedFact.Status.CONFIRMED, ExtractedFact.Status.CORRECTED]
                ).count()
                rejected = facts.filter(status=ExtractedFact.Status.REJECTED).count()
                details = {
                    'total_facts': total_facts,
                    'unreviewed_count': unreviewed,
                    'confirmed_count': confirmed,
                    'rejected_count': rejected,
                }
                if total_facts == 0:
                    status = 'not_started'
                    action_label = 'Review Extracted Facts'
                elif unreviewed > 0:
                    status = 'in_progress'
                    action_label = f'Review Facts ({unreviewed} pending)'
                else:
                    status = 'completed'
                    action_label = 'View Reviewed Facts'

        elif step_id == 'gaps_evidence':
            if not sprint:
                status = 'not_started'
                block_reason = 'Select a sprint first (Step 2).'
            else:
                gaps = sprint.gaps.all()
                active_gaps = gaps.filter(status__in=GapItem.ACTIVE_STATUSES)
                blocking_gaps = active_gaps.filter(priority=GapItem.Priority.BLOCKING)
                open_requests = EvidenceRequest.objects.filter(
                    sprint=sprint, status__in=['pending', 'submitted']
                )

                details = {
                    'total_gaps': gaps.count(),
                    'active_gaps_count': active_gaps.count(),
                    'blocking_gaps_count': blocking_gaps.count(),
                    'open_evidence_requests': open_requests.count(),
                }

                if blocking_gaps.exists():
                    status = 'needs_attention'
                    action_label = f'Resolve Blocking Gaps ({blocking_gaps.count()})'
                elif active_gaps.exists() or open_requests.exists():
                    status = 'in_progress'
                    action_label = 'Review Gaps & Evidence'
                elif gaps.exists() and not active_gaps.exists() and not open_requests.exists():
                    status = 'completed'
                    action_label = 'View Resolved Gaps'
                else:
                    # Gaps not yet generated or clean pass
                    if sprint.facts.exists() and not sprint.facts.filter(status=ExtractedFact.Status.EXTRACTED).exists():
                        status = 'completed'
                        action_label = 'View Gaps Dashboard'
                    else:
                        status = 'not_started'
                        action_label = 'Review Gaps'

        elif step_id == 'live_cri':
            if not sprint:
                status = 'not_started'
                block_reason = 'Select a sprint first (Step 2).'
            else:
                has_run = sprint.scoring_runs.exists()
                overall_cri = sprint.overall_cri
                details = {
                    'has_scoring_run': has_run,
                    'overall_cri': overall_cri,
                    'confidence_score': sprint.confidence_score,
                }
                if has_run or overall_cri is not None:
                    status = 'completed'
                    action_label = 'View Live CRI Preview'
                elif sprint.status in [Sprint.Status.SCORING, Sprint.Status.REVIEWING]:
                    status = 'in_progress'
                    action_label = 'Calculate Live CRI'
                else:
                    status = 'not_started'
                    action_label = 'View Live CRI'

        elif step_id == 'baseline_approval':
            if not sprint:
                status = 'not_started'
                block_reason = 'Select a sprint first (Step 2).'
            else:
                latest_baseline = sprint.baselines.first()
                baseline_status = latest_baseline.status if latest_baseline else None
                is_provisional = baseline_status == Baseline.Status.PROVISIONAL
                is_approved = baseline_status == Baseline.Status.APPROVED
                details = {
                    'baseline_status': baseline_status,
                    'is_approved': is_approved,
                    'is_provisional': is_provisional,
                    'approval_label': 'Provisional Approval' if is_provisional else ('Fully Approved' if is_approved else 'Not Approved'),
                }
                if latest_baseline:
                    if is_approved:
                        status = 'completed'
                        action_label = 'View Approved Baseline'
                    elif is_provisional:
                        status = 'completed'
                        action_label = 'View Provisional Baseline'
                    elif latest_baseline.status == Baseline.Status.RETURNED:
                        status = 'needs_attention'
                        action_label = 'Address Returned Baseline'
                    else:
                        status = 'in_progress'
                        action_label = 'Complete Baseline Approval'
                elif sprint.status in [
                    Sprint.Status.BASELINE_APPROVED,
                    Sprint.Status.REPORT_READY,
                    Sprint.Status.COMPLETED,
                ]:
                    status = 'completed'
                    action_label = 'View Approved Baseline'
                elif sprint.status == Sprint.Status.BASELINE_PENDING:
                    status = 'in_progress'
                    action_label = 'Review Pending Baseline'
                else:
                    status = 'not_started'
                    action_label = 'Review Baseline Approval'
                    if not sprint.scoring_runs.exists() and sprint.overall_cri is None:
                        block_reason = 'View or calculate Live CRI first (Step 7).'

        elif step_id == 'recommendations':
            if not sprint:
                status = 'not_started'
                block_reason = 'Select a sprint first (Step 2).'
            else:
                recs = sprint.recommendations.all()
                total_recs = recs.count()
                accepted_or_edited = recs.filter(
                    status__in=[
                        Recommendation.Status.ACCEPTED,
                        Recommendation.Status.EDITED,
                        Recommendation.Status.COMPLETED,
                    ]
                ).count()
                details = {
                    'total_recommendations': total_recs,
                    'accepted_or_edited_count': accepted_or_edited,
                }
                if total_recs > 0:
                    if accepted_or_edited > 0:
                        status = 'completed'
                        action_label = 'View Recommendations'
                    else:
                        status = 'in_progress'
                        action_label = 'Review Recommendations'
                else:
                    status = 'not_started'
                    action_label = 'Review Recommendations'
                    if sprint.status not in Sprint.BASELINE_LOCKED_STATUSES:
                        block_reason = 'Baseline approval is recommended to lock recommendations (Step 8).'

        elif step_id == 'transformation_plan':
            if not sprint:
                status = 'not_started'
                block_reason = 'Select a sprint first (Step 2).'
            else:
                recs_count = sprint.recommendations.count()
                details = {
                    'recommendations_count': recs_count,
                    'sprint_status': sprint.status,
                }
                if sprint.status in [
                    Sprint.Status.BASELINE_APPROVED,
                    Sprint.Status.REPORT_READY,
                    Sprint.Status.COMPLETED,
                ] and recs_count > 0:
                    status = 'completed'
                    action_label = 'Open Transformation Plan'
                elif recs_count > 0:
                    status = 'in_progress'
                    action_label = 'View Plan Horizons'
                else:
                    status = 'not_started'
                    action_label = 'Open Transformation Plan'

        elif step_id == 'reports':
            if not sprint:
                status = 'not_started'
                block_reason = 'Select a sprint first (Step 2).'
            else:
                reports = sprint.reports.all()
                ready_reports = reports.filter(status=Report.Status.READY)
                generating_reports = reports.filter(status=Report.Status.GENERATING)
                failed_reports = reports.filter(status=Report.Status.FAILED)
                has_approved_baseline = sprint.baselines.filter(
                    status__in=[Baseline.Status.APPROVED, Baseline.Status.PROVISIONAL]
                ).exists() or sprint.status in Sprint.BASELINE_LOCKED_STATUSES

                details = {
                    'total_reports': reports.count(),
                    'ready_count': ready_reports.count(),
                    'has_approved_baseline': has_approved_baseline,
                }

                if ready_reports.exists() or sprint.status in [
                    Sprint.Status.REPORT_READY,
                    Sprint.Status.COMPLETED,
                ]:
                    status = 'completed'
                    action_label = 'Download & View Report'
                elif generating_reports.exists():
                    status = 'in_progress'
                    action_label = 'Report Generating...'
                elif failed_reports.exists():
                    status = 'needs_attention'
                    action_label = 'Retry Report Generation'
                else:
                    status = 'not_started'
                    action_label = 'Generate Report'

                if not has_approved_baseline and status == 'not_started':
                    block_reason = 'Generating a formal Discovery Report requires an approved baseline (Step 8).'

        # Check skip state:
        # If user marked this step as skipped and it's not already completed in real life:
        is_skipped = step_id in skipped_step_keys
        if is_skipped and status != 'completed':
            status = 'skipped'

        if status == 'completed':
            completed_count += 1
        elif status == 'skipped':
            skipped_count += 1

        steps.append({
            'id': step_id,
            'number': num,
            'title': title,
            'purpose': purpose,
            'status': status,
            'action_label': action_label,
            'target_path': target_path,
            'tour_target': cfg.get('tour_target'),
            'tour_location': cfg.get('tour_location'),
            'is_authorized': is_authorized,
            'block_reason': block_reason,
            'details': details,
        })

    # Pick the one current guide step to show:
    # First authorized step in sequence that is NOT completed and NOT skipped.
    current_step = None
    for step in steps:
        if step['is_authorized'] and step['status'] not in ('completed', 'skipped'):
            current_step = step
            break

    # If all authorized steps are either completed or skipped, check if any is skipped:
    if not current_step and skipped_count > 0:
        # All incomplete steps were skipped
        current_step_id = None
        current_step_number = None
    elif current_step:
        current_step_id = current_step['id']
        current_step_number = current_step['number']
    else:
        current_step_id = None
        current_step_number = None

    return {
        'current_step_id': current_step_id,
        'current_step_number': current_step_number,
        'current_step': current_step,
        'steps': steps,
        'is_dismissed': is_dismissed,
        'completed_count': completed_count,
        'skipped_count': skipped_count,
        'total_steps': len(steps),
        'menu_tours': menu_tours,
        'sprint_id': sprint_id_str or None,
        'institution_id': str(institution.id) if institution else None,
        'institution_name': institution.name if institution else None,
        'sprint_code': sprint.sprint_code if sprint else None,
    }


def update_menu_tour(
    user: User,
    menu_key: str,
    status: str,
    sprint_id: Optional[str] = None,
    institution_id: Optional[str] = None,
) -> Dict[str, Any]:
    """Persist status of a contextual menu tour ('completed', 'dismissed', 'in_progress', 'reset').

    Does NOT modify any underlying platform business data.
    """
    institution = resolve_accessible_institution(user, institution_id)
    sprint = resolve_accessible_sprint(user, institution, sprint_id) if sprint_id else None
    if sprint and not institution:
        institution = sprint.institution

    state = get_user_guide_state(user, institution, sprint)
    tours = dict(getattr(state, 'menu_tours', {}) or {})
    tours[menu_key] = {
        'status': status,
        'updated_at': timezone.now().isoformat(),
    }
    state.menu_tours = tours
    try:
        state.save(update_fields=['menu_tours', 'updated_at'])
    except Exception as exc:
        logger.warning('Failed to save menu_tours in UserGuideState: %s', exc)

    return get_guide_status(user, sprint_id=sprint_id, institution_id=institution_id)


def skip_guide_step(
    user: User,
    step_id: str,
    sprint_id: Optional[str] = None,
    institution_id: Optional[str] = None,
    skipped: bool = True,
) -> Dict[str, Any]:
    """Persist a skip or un-skip for a step.

    Crucially: DOES NOT touch any institution, sprint, document, fact,
    gap, baseline, recommendation, or report row.
    """
    institution = resolve_accessible_institution(user, institution_id)
    sprint = resolve_accessible_sprint(user, institution, sprint_id)
    if sprint and not institution:
        institution = sprint.institution

    state = get_user_guide_state(user, institution, sprint)
    current_skips = list(state.skipped_steps or [])

    if skipped:
        if step_id not in current_skips:
            current_skips.append(step_id)
    else:
        if step_id in current_skips:
            current_skips.remove(step_id)

    state.skipped_steps = current_skips
    state.save(update_fields=['skipped_steps', 'updated_at'])

    return get_guide_status(user, sprint_id=sprint_id, institution_id=institution_id)


def set_guide_dismissed(
    user: User,
    dismissed: bool,
    sprint_id: Optional[str] = None,
    institution_id: Optional[str] = None,
) -> Dict[str, Any]:
    """Dismiss or reopen the guide card."""
    institution = resolve_accessible_institution(user, institution_id)
    sprint = resolve_accessible_sprint(user, institution, sprint_id)
    if sprint and not institution:
        institution = sprint.institution

    state = get_user_guide_state(user, institution, sprint)
    state.is_dismissed = dismissed
    if dismissed:
        state.dismissed_at = timezone.now()
    state.save(update_fields=['is_dismissed', 'dismissed_at', 'updated_at'])

    return get_guide_status(user, sprint_id=sprint_id, institution_id=institution_id)


def reset_guide(
    user: User,
    sprint_id: Optional[str] = None,
    institution_id: Optional[str] = None,
) -> Dict[str, Any]:
    """Reset all skips and dismissed status so user can walk through again."""
    institution = resolve_accessible_institution(user, institution_id)
    sprint = resolve_accessible_sprint(user, institution, sprint_id)
    if sprint and not institution:
        institution = sprint.institution

    state = get_user_guide_state(user, institution, sprint)
    state.skipped_steps = []
    state.is_dismissed = False
    state.dismissed_at = None
    state.save(update_fields=['skipped_steps', 'is_dismissed', 'dismissed_at', 'updated_at'])

    return get_guide_status(user, sprint_id=sprint_id, institution_id=institution_id)
